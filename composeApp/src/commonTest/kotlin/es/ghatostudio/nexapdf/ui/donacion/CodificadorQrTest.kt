/**
 * Verificacion del generador de QR contra una implementacion independiente.
 *
 * Las matrices esperadas las produjo la biblioteca `qrcode` de Python, otra
 * implementacion de la misma norma, forzando modo byte para que ambas codifiquen
 * igual. Comparar la matriz entera valida de una sola vez la codificacion, el
 * Reed-Solomon, el reparto en bloques, el entrelazado, la colocacion en zigzag y
 * la informacion de formato y version: si cualquiera de esas piezas se desviara,
 * la matriz saldria distinta.
 *
 * La comparacion fija la mascara. La razon es que las dos implementaciones
 * eligen mascaras distintas y las dos tienen razon: la norma manda evaluar la
 * penalizacion sobre el simbolo completo, informacion de formato incluida, que
 * es lo que hace NexaPDF, mientras que `qrcode` la evalua con esos modulos a
 * cero. Ambas mascaras dan codigos validos, asi que se fija la mascara para
 * comparar el resto, y aparte se conserva la matriz que produce la app de verdad.
 *
 * Que las matrices con mascara automatica son legibles no es una suposicion: se
 * decodificaron con el detector de QR de OpenCV, un tercer motor independiente,
 * y las siete devolvieron el texto original.
 *
 * Referencias reproducibles con: python tools/generar_referencias_qr.py
 */
class CodificadorQrTest {

    private data class Caso(
        val texto: String,
        val nivel: CodificadorQr.NivelCorreccion,
        val version: Int,
        val mascara: Int,
        val esperada: String,
    )

    @Test
    fun coincide_con_la_implementacion_de_referencia() {
        CASOS.forEach { caso ->
            val matriz = CodificadorQr.generar(caso.texto, caso.nivel, caso.mascara)

            assertEquals(
                17 + 4 * caso.version,
                matriz.tamano,
                "Version equivocada para <<${caso.texto.take(30)}>>",
            )

            val obtenida = aTexto(matriz)
            if (obtenida != caso.esperada) {
                val distintos = caso.esperada.indices.filter { caso.esperada[it] != obtenida[it] }
                val donde = distintos.take(12)
                    .joinToString { "(${it % matriz.tamano},${it / matriz.tamano})" }
                error(
                    "<<${caso.texto.take(30)}>>: ${distintos.size} de ${caso.esperada.length} " +
                        "modulos distintos. Primeros: $donde" + "\n" +
                        comparar(caso.esperada, obtenida, matriz.tamano),
                )
            }
        }
    }

    @Test
    fun la_version_elegida_es_la_mas_pequena_que_cabe() {
        CASOS.forEach { caso ->
            val matriz = CodificadorQr.generar(caso.texto, caso.nivel)
            assertEquals(
                17 + 4 * caso.version,
                matriz.tamano,
                "No se eligio la version minima para <<${caso.texto.take(30)}>>",
            )
        }
    }

    @Test
    fun el_qr_de_donacion_no_cambia() {
        // Golden master del codigo que se muestra de verdad en la app, con la
        // mascara que elige NexaPDF. Se comprobo con OpenCV que decodifica al
        // enlace correcto; si esta matriz cambia sin querer, la prueba avisa.
        val matriz = CodificadorQr.generar(
            "https://revolut.me/brais2oz6",
            CodificadorQr.NivelCorreccion.MEDIO,
        )
        assertEquals(QR_DONACION, aTexto(matriz))
    }

    @Test
    fun el_texto_que_no_cabe_falla_de_forma_clara() {
        assertFailsWith<CodificadorQr.TextoDemasiadoLargo> {
            CodificadorQr.generar("x".repeat(500), CodificadorQr.NivelCorreccion.MAXIMO)
        }
    }

    @Test
    fun los_patrones_de_busqueda_estan_en_las_tres_esquinas() {
        val matriz = CodificadorQr.generar("NexaPDF", CodificadorQr.NivelCorreccion.MEDIO)
        val ultima = matriz.tamano - 1
        listOf(0 to 0, ultima - 6 to 0, 0 to (ultima - 6)).forEach { (origenX, origenY) ->
            assertTrue(matriz[origenX, origenY], "Falta el borde del buscador")
            assertTrue(matriz[origenX + 3, origenY + 3], "Falta el centro del buscador")
            assertTrue(!matriz[origenX + 1, origenY + 1], "Falta el anillo claro del buscador")
        }
    }

    @Test
    fun fuera_de_la_matriz_no_hay_modulos_oscuros() {
        // El componente que pinta el QR consulta con margen; devolver claro en
        // vez de romper es lo que permite dibujar la zona de silencio.
        val matriz = CodificadorQr.generar("NexaPDF", CodificadorQr.NivelCorreccion.MEDIO)
        assertTrue(!matriz[-1, 0])
        assertTrue(!matriz[0, -1])
        assertTrue(!matriz[matriz.tamano, 0])
        assertTrue(!matriz[0, matriz.tamano])
    }

    private fun aTexto(matriz: CodificadorQr.MatrizQr): String = buildString {
        for (y in 0 until matriz.tamano) {
            for (x in 0 until matriz.tamano) append(if (matriz[x, y]) '1' else '0')
        }
    }

    /** Pinta las dos matrices lado a lado para ver que se descoloca. */
    private fun comparar(esperada: String, obtenida: String, tamano: Int): String = buildString {
        appendLine("esperada".padEnd(tamano + 4) + "obtenida")
        for (y in 0 until tamano) {
            val filaE = esperada.substring(y * tamano, (y + 1) * tamano)
            val filaO = obtenida.substring(y * tamano, (y + 1) * tamano)
            append(filaE.replace('1', '#').replace('0', '.'))
            append("    ")
            append(filaO.replace('1', '#').replace('0', '.'))
            if (filaE != filaO) append("  <-")
            appendLine()
        }
    }

